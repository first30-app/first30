def set_text(p, text):
    runs = p.runs
    runs[0].text = text
    for r in runs[1:]:
        r._r.getparent().remove(r._r)


def fill_cell(cell, items):
    """양식의 입력 상자(일반 텍스트 콘텐츠 컨트롤, 태그로 접수 내용을 뽑는다) 안에 내용을 넣는다.
    items: str 문단 또는 (머리말, 본문) 튜플. 일반 텍스트 컨트롤은 한 가지 서식만 담으므로 한 런 안에서 줄바꿈으로 나눈다."""
    from docx.oxml import OxmlElement
    from docx.oxml.ns import qn
    tc = cell._tc
    sdt = tc.find('.//' + qn('w:sdt'))
    assert sdt is not None, '입력 상자(콘텐츠 컨트롤)를 찾지 못했습니다'
    para = sdt.getparent()
    # 상자 밖에 남은 빈 강조 런을 지운다
    for r in list(para.findall(qn('w:r'))):
        if not ''.join(t.text or '' for t in r.findall(qn('w:t'))).strip():
            para.remove(r)
    texts = [f'{h}{b}' if isinstance(it, tuple) else it for it in items for (h, b) in [it if isinstance(it, tuple) else ('', it)]]
    pr = sdt.find(qn('w:sdtPr'))
    tx = pr.find(qn('w:text'))
    if tx is not None and len(texts) > 1:
        tx.set(qn('w:multiLine'), '1')  # 여러 줄 입력 허용 (한 줄 상자에 여러 항목을 넣을 때)
    content = sdt.find(qn('w:sdtContent'))
    for child in list(content):
        content.remove(child)
    run = OxmlElement('w:r')
    for k, line in enumerate(texts):
        if k:
            run.append(OxmlElement('w:br'))
            run.append(OxmlElement('w:br'))
        t = OxmlElement('w:t')
        t.set('{http://www.w3.org/XML/1998/namespace}space', 'preserve')
        t.text = line
        run.append(t)
    content.append(run)


